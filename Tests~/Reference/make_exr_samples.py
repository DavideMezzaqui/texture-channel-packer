#!/usr/bin/env python3
"""
Writes Tests/Editor/Core/ExrSamples.cs: small OpenEXR files produced by the OpenEXR library,
embedded as base64 so the Unity tests can check every compression of the built-in reader
without Python. Pixel values follow formulas that ExrSamples.cs reproduces.

Requirements: pip install numpy OpenEXR
Usage: python3 make_exr_samples.py
"""
import base64
import os
import tempfile

import numpy as np
import OpenEXR
import Imath

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "..", "Tests", "Editor", "Core", "ExrSamples.cs")

RGBA_W, RGBA_H = 7, 41
GRAY_W, GRAY_H = 9, 37
SPECIALS = [0x7E00, 0x7C00, 0xFC00, 0x8000, 0x0001, 0x7BFF]  # NaN, +Inf, -Inf, -0, smallest subnormal, largest half


def rgba_half_bits(x, y, c):
    i = x + y * RGBA_W
    if i % 31 == c:
        return SPECIALS[(i // 31) % len(SPECIALS)]
    return 0x3C00 + ((x * 7 + y * 13 + c * 101) % 1024)


def gray_float_bits(x, y):
    i = x + y * GRAY_W
    if i % 17 == 5:
        return 0x7F800000  # +Inf
    if i % 17 == 9:
        return 0x80000000  # -0
    return int(np.array([(x - 3) * 0.375 + y * 1.5], dtype=np.float32).view(np.uint32)[0])


def write(path, w, h, compression, channels):
    header = OpenEXR.Header(w, h)
    header["compression"] = Imath.Compression(getattr(Imath.Compression, compression + "_COMPRESSION"))
    header["channels"] = {name: Imath.Channel(ptype) for name, (ptype, _) in channels.items()}
    f = OpenEXR.OutputFile(path, header)
    f.writePixels({name: data for name, (_, data) in channels.items()})
    f.close()
    with open(path, "rb") as source:
        return base64.b64encode(source.read()).decode("ascii")


def main():
    half = Imath.PixelType(Imath.PixelType.HALF)
    single = Imath.PixelType(Imath.PixelType.FLOAT)
    rgba = {}
    for c, name in enumerate("RGBA"):
        bits = np.array([[rgba_half_bits(x, y, c) for x in range(RGBA_W)] for y in range(RGBA_H)], dtype="<u2")
        rgba[name] = (half, bits.tobytes())
    gray = np.array([[gray_float_bits(x, y) for x in range(GRAY_W)] for y in range(GRAY_H)], dtype="<u4")

    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for compression in ("NO", "RLE", "ZIPS", "ZIP", "PIZ"):
            data = write(os.path.join(tmp, "rgba.exr"), RGBA_W, RGBA_H, compression, rgba)
            entries.append(("Rgba", compression, data))
        for compression in ("PIZ", "ZIP"):
            data = write(os.path.join(tmp, "gray.exr"), GRAY_W, GRAY_H, compression, {"Y": (single, gray.tobytes())})
            entries.append(("GrayFloat", compression, data))

    def table(kind):
        lines = []
        for k, compression, data in entries:
            if k != kind:
                continue
            chunks = [data[i:i + 120] for i in range(0, len(data), 120)]
            body = "\" +\n                \"".join(chunks)
            lines.append(f"            (\"{compression}\",\n                \"{body}\")")
        return ",\n".join(lines)

    specials = ", ".join(f"0x{s:04X}" for s in SPECIALS)
    source = f"""// Generated by Tests~/Reference/make_exr_samples.py with the OpenEXR library. Do not edit.
using System;

namespace DAVFX.TextureChannelPacker.Tests
{{
    /// <summary>
    /// Small OpenEXR files written by the OpenEXR library, one per compression, so the Unity tests can check
    /// the built-in reader without Python. Pixel values follow <see cref="RgbaHalfBits"/> and <see cref="GrayFloatBits"/>.
    /// </summary>
    public static class ExrSamples
    {{
        public const int RgbaWidth = {RGBA_W};
        public const int RgbaHeight = {RGBA_H};
        public const int GrayWidth = {GRAY_W};
        public const int GrayHeight = {GRAY_H};

        static readonly ushort[] s_Specials = {{ {specials} }};

        /// <summary>RGBA half files ({RGBA_W}x{RGBA_H}) with NaN, infinities, -0, subnormal and largest half values.</summary>
        public static readonly (string compression, string base64)[] Rgba =
        {{
{table("Rgba")}
        }};

        /// <summary>Single Y float channel files ({GRAY_W}x{GRAY_H}).</summary>
        public static readonly (string compression, string base64)[] GrayFloat =
        {{
{table("GrayFloat")}
        }};

        public static ushort RgbaHalfBits(int x, int y, int c)
        {{
            int i = x + y * RgbaWidth;
            if (i % 31 == c)
                return s_Specials[(i / 31) % s_Specials.Length];
            return (ushort)(0x3C00 + ((x * 7 + y * 13 + c * 101) % 1024));
        }}

        public static uint GrayFloatBits(int x, int y)
        {{
            int i = x + y * GrayWidth;
            if (i % 17 == 5)
                return 0x7F800000u;
            if (i % 17 == 9)
                return 0x80000000u;
            return BitConverter.ToUInt32(BitConverter.GetBytes((x - 3) * 0.375f + y * 1.5f), 0);
        }}

        public static byte[] Bytes(string base64)
        {{
            return Convert.FromBase64String(base64);
        }}
    }}
}}
"""
    with open(TARGET, "w", newline="\n") as f:
        f.write(source)
    print(f"Wrote {os.path.normpath(TARGET)} ({len(entries)} files)")


if __name__ == "__main__":
    main()
